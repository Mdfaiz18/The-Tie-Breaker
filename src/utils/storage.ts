import { DecisionAnalysis } from '../types/decision';

const STORAGE_KEY = 'the_tiebreaker_saved_decisions_v1';

export function getSavedDecisions(): DecisionAnalysis[] {
  try {
    const data = localStorage.getItem(STORAGE_KEY);
    if (!data) return [];
    return JSON.parse(data);
  } catch (e) {
    console.error('Failed to load saved decisions:', e);
    return [];
  }
}

export function saveDecision(decision: DecisionAnalysis): void {
  try {
    const existing = getSavedDecisions();
    const filtered = existing.filter((d) => d.id !== decision.id);
    const updated = [decision, ...filtered].slice(0, 50); // keep up to 50
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed to save decision:', e);
  }
}

export function deleteDecision(id: string): void {
  try {
    const existing = getSavedDecisions();
    const updated = existing.filter((d) => d.id !== id);
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Failed to delete decision:', e);
  }
}

export function exportDecisionAsMarkdown(decision: DecisionAnalysis): string {
  let md = `# Decision Report: ${decision.title}\n\n`;
  md += `**Date:** ${new Date(decision.createdAt).toLocaleDateString()}\n`;
  md += `**Evaluation Lens:** ${decision.persona.replace('_', ' ').toUpperCase()}\n`;
  if (decision.context) {
    md += `**Context:** ${decision.context}\n`;
  }
  md += `\n---\n\n`;

  md += `## 🏆 The Tiebreaker Verdict: ${decision.verdict.winnerOptionName}\n\n`;
  md += `> **${decision.verdict.headline}**\n\n`;
  md += `**Confidence Rating:** ${decision.verdict.confidencePercentage}%\n\n`;
  md += `### Executive Summary\n${decision.verdict.executiveSummary}\n\n`;

  md += `### Core Deciding Factors\n`;
  decision.verdict.coreDecidingFactors.forEach((factor) => {
    md += `- ${factor}\n`;
  });

  md += `\n### Devil's Advocate / When the other option wins\n`;
  md += `- **Alternative Scenario:** ${decision.verdict.devilsAdvocate.alternativeScenario}\n`;
  md += `- **Potential Regret:** ${decision.verdict.devilsAdvocate.potentialRegret}\n`;
  md += `- **When to Choose The Other:** ${decision.verdict.devilsAdvocate.whenToChooseTheOther}\n\n`;

  md += `### Blind Spots & Mitigations\n`;
  decision.verdict.blindSpots.forEach((b) => {
    md += `#### ⚠️ ${b.title}\n- **Warning:** ${b.warning}\n- **Mitigation:** ${b.mitigation}\n\n`;
  });

  md += `---\n\n## ⚖️ Pros & Cons Breakdown\n\n`;
  decision.prosAndCons.forEach((pc) => {
    md += `### Option: ${pc.optionName}\n`;
    md += `*${pc.summary}*\n\n`;
    md += `#### Pros\n`;
    pc.pros.forEach((p) => {
      md += `- **${p.text}** [${p.category} | Impact: ${p.impact} | Score: +${p.score}/10]: ${p.explanation}\n`;
    });
    md += `\n#### Cons\n`;
    pc.cons.forEach((c) => {
      md += `- **${c.text}** [${c.category} | Impact: ${c.impact} | Severity: -${c.score}/10]: ${c.explanation}\n`;
    });
    md += `\n`;
  });

  md += `---\n\n## 📊 Criteria Comparison Matrix\n\n`;
  md += `| Criterion | Weight | ${decision.options.map((o) => o.name).join(' | ')} |\n`;
  md += `|---|---|${decision.options.map(() => '---|').join('')}\n`;
  decision.comparisonMatrix.criteria.forEach((crit) => {
    const row = decision.comparisonMatrix.scores.find((s) => s.criteriaId === crit.id);
    const scoreCols = decision.options
      .map((opt) => {
        const rating = row?.ratings[opt.id]?.score ?? '-';
        return `${rating}/10`;
      })
      .join(' | ');
    md += `| **${crit.name}** | ${crit.weight}x | ${scoreCols} |\n`;
  });
  md += `\n`;

  md += `---\n\n## 🧭 SWOT Analysis\n\n`;
  decision.swot.forEach((s) => {
    md += `### ${s.optionName}\n`;
    md += `*${s.strategicSummary}*\n\n`;
    md += `- **Strengths:** ${s.strengths.join('; ')}\n`;
    md += `- **Weaknesses:** ${s.weaknesses.join('; ')}\n`;
    md += `- **Opportunities:** ${s.opportunities.join('; ')}\n`;
    md += `- **Threats:** ${s.threats.join('; ')}\n\n`;
  });

  md += `---\n*Generated by The Tiebreaker AI Decision Assistant*`;
  return md;
}
